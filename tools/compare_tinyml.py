"""Compare the int8 C model (firmware/components/tinyml) with Derya's float model.

Runs the C host test and cloud/derya_model.py on the same recorded log and
reports, over every complete 24 h window:
  - the largest forecast difference in VWC points (int8 vs float),
  - how often the decision (now / when_minutes, the baseline's rule) agrees.

Usage
  make -C firmware/components/tinyml/test
  python tools/compare_tinyml.py ../sagriot-dss data/snapshot_0909.csv
  ... --write-expected experiments/tinyml_bench/main/tinyml_expected.c
      (the float model's answers for the on-chip check, same samples as
       firmware/components/replay)
"""
import argparse
import csv
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
C_TEST = REPO / "firmware/components/tinyml/test/test_tinyml"
CONTEXT, HORIZON, STEP, WARN_LOW = 288, 36, 5, 70.0
sys.path.insert(0, str(REPO / "cloud"))


def decision(vwc_now, forecast, fc):
    line = (WARN_LOW - 0.05) / 100 * fc          # same threshold as baseline.c
    when = next(((k + 1) * STEP for k, v in enumerate(forecast) if v < line), -1)
    return vwc_now < line, when


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("dss", type=Path)
    p.add_argument("log")
    p.add_argument("--field-capacity", type=float, default=64.9)
    p.add_argument("--write-expected", type=Path, default=None)
    args = p.parse_args()

    sys.path.insert(0, str(args.dss))
    from sagriot.advise import load_recent
    import derya_model

    fc = args.field_capacity
    frame = load_recent(str(args.dss / args.log), hours=100000)[["soil_vwc", "air_temp", "air_humidity"]]
    if not C_TEST.exists():
        sys.exit(f"build the C test first: make -C {C_TEST.parent}")
    with tempfile.TemporaryDirectory() as tmp:
        data = Path(tmp) / "data.csv"
        frame.to_csv(data, index=False, header=["vwc", "air_temp", "air_humidity"],
                     float_format="%.6f", na_rep="nan")
        res = subprocess.run([str(C_TEST), str(data), str(fc)],
                             capture_output=True, text=True, check=True)
    print(res.stderr.strip())
    c_rows = {int(r["index"]): r for r in csv.DictReader(res.stdout.splitlines())}

    # VPD exactly as the node stores it (baseline.c compute_vpd, 3 decimals)
    t = frame["air_temp"].to_numpy(float)
    rh = frame["air_humidity"].to_numpy(float)
    es = 0.6108 * np.exp(17.27 * t / (t + 237.3))
    vpd = np.round(es - es * rh / 100, 3).astype(np.float32).astype(float)
    vwc = frame["soil_vwc"].to_numpy(float).astype(np.float32).astype(float)

    diffs, agree, compared, warns, mism = [], 0, 0, 0, []
    n = len(frame)
    exp_now, exp_when, exp_pred = [255] * n, [-2] * n, [float("nan")] * n
    for end in range(CONTEXT - 1, len(frame)):
        w, v = vwc[end - CONTEXT + 1:end + 1], vpd[end - CONTEXT + 1:end + 1]
        py = derya_model.predict(w, v, fc=fc)
        if py is None or end not in c_rows:
            if (py is None) != (end not in c_rows):
                mism.append((end, "window valid in one only"))
            continue
        r = c_rows[end]
        c = np.array([float(r[f"f{j}"]) for j in range(1, HORIZON + 1)])
        diffs.append(np.abs(c - py).max())
        now, when = decision(w[-1], py, fc)
        exp_now[end], exp_when[end], exp_pred[end] = int(now), when, float(py[-1])
        compared += 1
        warns += when != -1
        if (now, when) == (bool(int(r["now"])), int(r["when_minutes"])):
            agree += 1
        else:
            mism.append((end, f"python now={now} when={when} | C now={r['now']} when={r['when_minutes']}"))

    if not compared:
        sys.exit("no complete 24 h window")
    d = np.array(diffs)
    print(f"windows compared: {compared}  (with a warning: {warns})")
    print(f"forecast difference C vs float: max {d.max():.4f}, mean {d.mean():.4f} VWC points")
    print(f"same decision: {agree}/{compared} = {100 * agree / compared:.2f} %")
    for end, msg in mism[:10]:
        print(f"  sample {end}: {msg}")
    if args.write_expected:
        write_expected(args.write_expected, exp_now, exp_when, exp_pred, fc)


def write_expected(path, now, when, pred, fc):
    def rows(vals, fmt):
        return [",".join(fmt(v) for v in vals[i:i + 12]) + "," for i in range(0, len(vals), 12)]
    f = lambda v: "NAN" if not np.isfinite(v) else f"{v:.4f}f"
    lines = ["// Generated by tools/compare_tinyml.py: cloud/derya_model.py (float) on the",
             f"// replay log, field capacity {fc}. now = 255 marks windows that are not compared.",
             "#include <math.h>", '#include "tinyml_expected.h"',
             f"const uint8_t g_tm_now[{len(now)}] = {{", *rows(now, str), "};",
             f"const int16_t g_tm_when[{len(when)}] = {{", *rows(when, str), "};",
             f"const float g_tm_pred_3h[{len(pred)}] = {{", *rows(pred, f), "};", ""]
    Path(path).write_text("\n".join(lines))
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
