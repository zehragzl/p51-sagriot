"""Derya's linear model (cloud/derya_model.npz) -> int8 C source for the node.

  python tools/export_tinyml.py        # writes firmware/components/tinyml/tinyml_weights.c

Symmetric quantization, one float scale per output step and block
(w ~= q * scale[j]); the 36 biases stay float.
  soil weights (288 x 36)  int16   soil inputs are large (up to +-50 % FC),
                                   int8 here gave 0.19 VWC mean error
  VPD weights  (288 x 36)  int8    VPD inputs are ~1 kPa, int8 is enough
Layout q[i][j], input-major: the node reads the 24 h buffer once and adds
each input to all 36 outputs. Size: 20,736 + 10,368 + 2*144 + 144 = 31,536 bytes.
Forecast error vs the float model on the internship record: about 0.02 VWC.
"""
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "cloud" / "derya_model.npz"
OUT = ROOT / "firmware" / "components" / "tinyml" / "tinyml_weights.c"


def quantize(w, bits):
    top = 2 ** (bits - 1) - 1
    scale = np.abs(w).max(axis=0) / top
    scale[scale == 0] = 1.0
    q = np.clip(np.round(w / scale), -top, top).astype(np.int16 if bits == 16 else np.int8)
    return q, scale.astype(np.float32)


def c_array(ctype, name, q):
    rows = ["  {" + ",".join(str(int(v)) for v in row) + "}," for row in q]
    return [f"const {ctype} {name}[{q.shape[0]}][{q.shape[1]}] = {{", *rows, "};", ""]


def c_floats(name, v):
    return [f"const float {name}[{len(v)}] = {{", "  " + ", ".join(f"{x:.9g}f" for x in v), "};", ""]


def render(src=SRC):
    """Returns (C source text, size in bytes, max weight error)."""
    d = np.load(src)
    w, b = d["weights"].astype(np.float64), d["bias"].astype(np.float32)
    half = w.shape[0] // 2
    qs, ss = quantize(w[:half], 16)
    qv, sv = quantize(w[half:], 8)
    deq = np.vstack([qs * ss.astype(np.float64), qv * sv.astype(np.float64)])
    err = np.abs(deq - w).max()

    lines = ["// Generated by tools/export_tinyml.py from cloud/derya_model.npz. Do not edit.",
             f"// Soil weights int16, VPD weights int8, per-output scales. Max weight error {err:.2e}.",
             '#include "tinyml_weights.h"', ""]
    lines += c_array("int16_t", "g_tinyml_q_soil", qs) + c_array("int8_t", "g_tinyml_q_vpd", qv)
    lines += c_floats("g_tinyml_scale_soil", ss) + c_floats("g_tinyml_scale_vpd", sv)
    lines += c_floats("g_tinyml_bias", b)
    size = qs.nbytes + qv.nbytes + ss.nbytes + sv.nbytes + b.nbytes
    return "\n".join(lines), size, err


def main():
    text, size, err = render()
    OUT.write_text(text)
    print(f"{OUT.relative_to(ROOT)}: {size} bytes, max weight error {err:.2e}")


if __name__ == "__main__":
    main()
